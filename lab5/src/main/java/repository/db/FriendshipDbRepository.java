package repository.db;

import domain.Friendship;
import domain.Tuple;
import domain.validators.Validator;
import exceptions.RepositoryException;
import repository.Repository;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;

/**
 * JDBC repository for friendships, backed by the {@code friendships} table of a PostgreSQL
 * database. The id of a friendship (the pair of user ids, smaller first) is already fully
 * known before save, so unlike users nothing is generated by the database here.
 * Every method opens its own connection (try-with-resources), so no connection is kept
 * open between calls.
 */
public class FriendshipDbRepository implements Repository<Tuple<Long, Long>, Friendship> {
    private final Validator<Friendship> validator;
    private final String url;
    private final String user;
    private final String password;

    /**
     * @param validator the validation strategy for friendships
     * @param url       the JDBC url of the database
     * @param user      the database user
     * @param password  the database password
     */
    public FriendshipDbRepository(Validator<Friendship> validator, String url, String user, String password) {
        this.validator = validator;
        this.url = url;
        this.user = user;
        this.password = password;
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be reached
     */
    @Override
    public Friendship findOne(Tuple<Long, Long> id) {
        if (id == null) {
            throw new IllegalArgumentException("id must not be null");
        }
        String sql = "SELECT id1, id2, friends_from FROM friendships WHERE id1 = ? AND id2 = ?";
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id.getLeft());
            statement.setLong(2, id.getRight());
            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next() ? toFriendship(resultSet) : null;
            }
        } catch (SQLException e) {
            throw new RepositoryException("Cannot read the friendship " + id + " from the database: "
                    + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be reached
     */
    @Override
    public Iterable<Friendship> findAll() {
        String sql = "SELECT id1, id2, friends_from FROM friendships";
        List<Friendship> result = new ArrayList<>();
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement statement = connection.prepareStatement(sql);
             ResultSet resultSet = statement.executeQuery()) {
            while (resultSet.next()) {
                result.add(toFriendship(resultSet));
            }
            return result;
        } catch (SQLException e) {
            throw new RepositoryException("Cannot read the friendships from the database: " + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be reached or a constraint is violated
     */
    @Override
    public Friendship save(Friendship entity) {
        if (entity == null) {
            throw new IllegalArgumentException("entity must not be null");
        }
        validator.validate(entity);
        if (findOne(entity.getId()) != null) {
            return entity;
        }
        String sql = "INSERT INTO friendships (id1, id2, friends_from) VALUES (?, ?, ?)";
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, entity.getIdUser1());
            statement.setLong(2, entity.getIdUser2());
            statement.setTimestamp(3, Timestamp.valueOf(entity.getDate()));
            statement.executeUpdate();
            return null;
        } catch (SQLException e) {
            throw new RepositoryException("Cannot save the friendship " + entity.getId() + ": "
                    + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be reached
     */
    @Override
    public Friendship delete(Tuple<Long, Long> id) {
        if (id == null) {
            throw new IllegalArgumentException("id must not be null");
        }
        String sql = "DELETE FROM friendships WHERE id1 = ? AND id2 = ? RETURNING id1, id2, friends_from";
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setLong(1, id.getLeft());
            statement.setLong(2, id.getRight());
            try (ResultSet resultSet = statement.executeQuery()) {
                return resultSet.next() ? toFriendship(resultSet) : null;
            }
        } catch (SQLException e) {
            throw new RepositoryException("Cannot delete the friendship " + id + ": " + e.getMessage(), e);
        }
    }

    /**
     * {@inheritDoc}
     *
     * @throws RepositoryException if the database cannot be reached
     */
    @Override
    public Friendship update(Friendship entity) {
        if (entity == null) {
            throw new IllegalArgumentException("entity must not be null");
        }
        validator.validate(entity);
        String sql = "UPDATE friendships SET friends_from = ? WHERE id1 = ? AND id2 = ?";
        try (Connection connection = DriverManager.getConnection(url, user, password);
             PreparedStatement statement = connection.prepareStatement(sql)) {
            statement.setTimestamp(1, Timestamp.valueOf(entity.getDate()));
            statement.setLong(2, entity.getIdUser1());
            statement.setLong(3, entity.getIdUser2());
            int rowsUpdated = statement.executeUpdate();
            return rowsUpdated == 0 ? entity : null;
        } catch (SQLException e) {
            throw new RepositoryException("Cannot update the friendship " + entity.getId() + ": "
                    + e.getMessage(), e);
        }
    }

    private Friendship toFriendship(ResultSet resultSet) throws SQLException {
        return new Friendship(resultSet.getLong("id1"), resultSet.getLong("id2"),
                resultSet.getTimestamp("friends_from").toLocalDateTime());
    }
}
